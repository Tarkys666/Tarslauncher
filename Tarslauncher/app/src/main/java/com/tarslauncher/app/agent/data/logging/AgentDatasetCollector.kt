package com.tarslauncher.app.agent.data.logging

import android.content.Context
import android.content.Intent
import androidx.core.content.FileProvider
import com.google.gson.Gson
import com.google.gson.JsonArray
import com.google.gson.JsonObject
import com.tarslauncher.app.agent.domain.model.AgentAction
import kotlinx.coroutines.Dispatchers
import kotlinx.coroutines.sync.Mutex
import kotlinx.coroutines.sync.withLock
import kotlinx.coroutines.withContext
import java.io.File
import java.text.SimpleDateFormat
import java.util.Date
import java.util.Locale

/**
 * Trajectory & Dataset Collector for training custom agent SLMs / LLMs.
 * Saves full interaction trajectories (system prompt, screen state, raw model response, action, execution feedback)
 * in industry-standard JSONL format (ShareGPT / ChatML) compatible with Axolotl, Unsloth, LLaMA-Factory and Hugging Face.
 */
class AgentDatasetCollector(private val context: Context) {

    private val datasetFile: File = File(context.filesDir, "tars_agent_dataset.jsonl")
    private val sessionLogFile: File = File(context.filesDir, "tars_agent_session.log")
    private val gson = Gson()
    private val mutex = Mutex()
    private val dateFormat = SimpleDateFormat("yyyy-MM-dd'T'HH:mm:ss.SSSZ", Locale.US)

    suspend fun recordStep(
        sessionId: String,
        step: Int,
        goal: String,
        systemPrompt: String,
        screenDump: String,
        rawModelResponse: String,
        parsedAction: AgentAction?,
        executionResult: String,
        provider: String,
        model: String,
        status: String
    ) = withContext(Dispatchers.IO) {
        mutex.withLock {
            val timestamp = dateFormat.format(Date())

            // 1. JSONL ShareGPT / ChatML training format
            val entryObj = JsonObject().apply {
                addProperty("id", "${sessionId}_step_$step")
                addProperty("session_id", sessionId)
                addProperty("step", step)
                addProperty("timestamp", timestamp)
                addProperty("goal", goal)
                addProperty("provider", provider)
                addProperty("model", model)
                addProperty("status", status)
                addProperty("execution_result", executionResult)

                // Standard SFT conversation array
                val conversations = JsonArray().apply {
                    // System prompt
                    add(JsonObject().apply {
                        addProperty("from", "system")
                        addProperty("value", systemPrompt)
                    })
                    // User prompt (Goal + Screen State Accessibility Tree)
                    val userPrompt = buildString {
                        appendLine("GÖREV: $goal")
                        appendLine("EKRAN:")
                        appendLine("<untrusted_screen_state>")
                        appendLine(screenDump)
                        append("</untrusted_screen_state>")
                    }
                    add(JsonObject().apply {
                        addProperty("from", "human")
                        addProperty("value", userPrompt)
                    })
                    // Assistant response (Raw JSON generated by LLM)
                    add(JsonObject().apply {
                        addProperty("from", "gpt")
                        addProperty("value", rawModelResponse)
                    })
                }
                add("conversations", conversations)

                // Metadata for filtering & preference modeling (DPO/RLHF)
                val metaObj = JsonObject().apply {
                    addProperty("parsed_action_type", parsedAction?.javaClass?.simpleName ?: "null")
                    addProperty("operational_signature", parsedAction?.toOperationalSignature() ?: "")
                    addProperty("thought", parsedAction?.thought ?: "")
                }
                add("metadata", metaObj)
            }

            datasetFile.appendText(entryObj.toString() + "\n", Charsets.UTF_8)

            // 2. Human-readable session log
            val logEntry = buildString {
                appendLine("[$timestamp] [SESSION: $sessionId] [ADIM: $step] [$provider / $model]")
                appendLine("GÖREV: $goal")
                appendLine("EKRAN BOYUTU: ${screenDump.length} karakter")
                appendLine("MODEL YANITI: $rawModelResponse")
                appendLine("EYLEM SONUCU: $executionResult ($status)")
                appendLine("--------------------------------------------------------------------------------")
            }
            sessionLogFile.appendText(logEntry, Charsets.UTF_8)
        }
    }

    suspend fun getDatasetCount(): Int = withContext(Dispatchers.IO) {
        mutex.withLock {
            if (!datasetFile.exists()) return@withContext 0
            runCatching {
                var lines = 0
                datasetFile.forEachLine { if (it.isNotBlank()) lines++ }
                lines
            }.getOrDefault(0)
        }
    }

    suspend fun clearDataset(): Boolean = withContext(Dispatchers.IO) {
        mutex.withLock {
            runCatching {
                if (datasetFile.exists()) datasetFile.delete()
                if (sessionLogFile.exists()) sessionLogFile.delete()
                true
            }.getOrDefault(false)
        }
    }

    fun getDatasetFile(): File = datasetFile
    fun getSessionLogFile(): File = sessionLogFile

    fun createExportIntent(context: Context): Intent? {
        if (!datasetFile.exists() || datasetFile.length() == 0L) {
            return null
        }

        val uri = FileProvider.getUriForFile(
            context,
            "${context.packageName}.fileprovider",
            datasetFile
        )

        return Intent(Intent.ACTION_SEND).apply {
            type = "text/plain"
            putExtra(Intent.EXTRA_STREAM, uri)
            putExtra(Intent.EXTRA_SUBJECT, "TARS Agent Eğitilebilir Veri Seti (.jsonl)")
            putExtra(Intent.EXTRA_TEXT, "TARS Launcher üzerinden toplanan otonom mobil ajan eğitim veri seti.")
            addFlags(Intent.FLAG_GRANT_READ_URI_PERMISSION)
        }
    }
}
